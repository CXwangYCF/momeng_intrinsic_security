"""RIPO-backed multi-endpoint batch client for MuSLR."""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Callable, Sequence
from urllib.parse import unquote, urlparse


def _load_ripo(ripo_root: Path) -> tuple[Any, Any, Any]:
    source_root = (ripo_root / "src").resolve()
    if not source_root.is_dir():
        raise FileNotFoundError(f"RIPO source directory does not exist: {source_root}")
    source_text = str(source_root)
    if source_text not in sys.path:
        sys.path.insert(0, source_text)
    # Keep the evaluation directory free of bytecode generated by this adapter.
    sys.dont_write_bytecode = True
    from pi_engine.executor.batch import run_batch
    from pi_engine.inference import PIVLMConfig, PIVLMPool

    return PIVLMConfig, PIVLMPool, run_batch


def _file_url_to_path(value: str) -> str:
    parsed = urlparse(value)
    if parsed.scheme not in {"", "file"}:
        raise ValueError(
            "RIPO batch inference requires local file:// images; "
            f"received URL scheme {parsed.scheme!r}"
        )
    if parsed.scheme == "file":
        if parsed.netloc not in {"", "localhost"}:
            path = f"//{parsed.netloc}{parsed.path}"
        else:
            path = parsed.path
    else:
        path = parsed.path or parsed.geturl()
    resolved = Path(unquote(path)).expanduser().resolve()
    if not resolved.is_file():
        raise FileNotFoundError(f"Local image does not exist: {resolved}")
    return str(resolved)


def to_ripo_messages(content: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Convert the runner's OpenAI content blocks to RIPO canonical blocks."""
    blocks: list[dict[str, Any]] = []
    for block in content:
        block_type = block.get("type")
        if block_type == "text":
            blocks.append({"type": "text", "text": str(block.get("text", ""))})
            continue
        if block_type == "image_url":
            image_url = block.get("image_url", {})
            if isinstance(image_url, dict):
                url = image_url.get("url")
            else:
                url = image_url
            if not isinstance(url, str) or not url:
                raise ValueError("image_url block is missing a URL")
            blocks.append({"type": "image", "path": _file_url_to_path(url)})
            continue
        raise ValueError(f"Unsupported MuSLR content block for RIPO: {block_type!r}")
    return [{"role": "user", "content": blocks}]


def _response_text(response: Any) -> str:
    if isinstance(response, dict):
        content = response.get("content", "")
    else:
        content = getattr(response, "content", "")
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(
            str(block.get("text", ""))
            for block in content
            if isinstance(block, dict) and block.get("type") == "text"
        )
    return str(content or "")


class _RipoBackendClient:
    def __init__(self, backend: Any, max_tokens: int, model: str) -> None:
        self.backend = backend
        self.max_tokens = max_tokens
        self.model = model

    def complete(self, content: list[dict[str, Any]]) -> tuple[str, dict[str, Any] | None, str | None]:
        metadata = self.backend.complete_with_metadata(
            messages=to_ripo_messages(content),
            max_tokens=self.max_tokens,
            temperature=0,
        )
        if not metadata.responses:
            raise RuntimeError(f"RIPO returned no response from {metadata.endpoint}")
        usage = dict(metadata.usage) if metadata.usage else None
        if usage is not None:
            usage["endpoint"] = metadata.endpoint
        return _response_text(metadata.responses[0]), usage, None


class RipoBatchClient:
    """Adapter exposing RIPO's endpoint pool and generic ``run_batch`` API."""

    uses_ripo_batch = True

    def __init__(
        self,
        endpoints: Sequence[str],
        *,
        ripo_root: Path,
        api_key: str,
        model: str,
        max_tokens: int,
        timeout: float,
        retries: int,
        endpoint_concurrency: int,
        image_url_mode: str,
    ) -> None:
        if not endpoints:
            raise ValueError("At least one RIPO endpoint is required")
        if endpoint_concurrency < 1:
            raise ValueError("endpoint_concurrency must be at least 1")
        PIVLMConfig, PIVLMPool, run_batch = _load_ripo(ripo_root)
        self._run_batch_impl = run_batch
        self.max_tokens = max_tokens
        self.model = model
        self.endpoints = tuple(endpoint.rstrip("/") for endpoint in endpoints)
        config = PIVLMConfig(
            endpoints=self.endpoints,
            model=model,
            api_key=api_key,
            timeout=timeout,
            image_url_mode=image_url_mode,
            max_tokens=max_tokens,
            temperature=0,
            max_try=max(1, retries + 1),
            wait_time=1.0 if retries else 0.0,
        )
        self.pool = PIVLMPool(
            endpoints=self.endpoints,
            config=config,
            pool_concurrency=endpoint_concurrency,
        )

    def complete(self, content: list[dict[str, Any]]) -> tuple[str, dict[str, Any] | None, str | None]:
        metadata = self.pool.complete_with_metadata(
            messages=to_ripo_messages(content),
            max_tokens=self.max_tokens,
            temperature=0,
        )
        if not metadata.responses:
            raise RuntimeError(f"RIPO returned no response from {metadata.endpoint}")
        usage = dict(metadata.usage) if metadata.usage else None
        if usage is not None:
            usage["endpoint"] = metadata.endpoint
        return _response_text(metadata.responses[0]), usage, None

    def run_batch(
        self,
        tasks: Sequence[Any],
        run_one: Callable[[Any, Any], Any],
        *,
        max_workers: int,
        task_id: Callable[[Any], str],
        on_outcome: Callable[[Any], None],
    ) -> Any:
        return self._run_batch_impl(
            tasks,
            run_one=lambda backend, task: run_one(
                _RipoBackendClient(backend, self.max_tokens, self.model), task
            ),
            client=self.pool,
            task_id=task_id,
            is_error=lambda record: record.get("status") == "failed",
            max_workers=max_workers,
            description="MuSLR inference",
            on_outcome=on_outcome,
            progress=False,
            thread_name_prefix="muslr-ripo-batch",
        )

    def close(self) -> None:
        self.pool.close()
